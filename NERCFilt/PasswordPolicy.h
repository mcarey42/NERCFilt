// PasswordPolicy.h - the password rules NERCFilt enforces.
//
// Defaults follow NERC CIP-007-6 R5.5:
//   R5.5.1  length of at least 8 characters
//   R5.5.2  at least 3 of: upper case, lower case, digit, non-alphanumeric
//
// Sites may make the policy stricter (never weaker) with DWORD values under
// HKLM\SOFTWARE\NERCFilt:
//   MinimumLength            8..256
//   MinimumCharacterClasses  3..4
// Out-of-range values are clamped into those ranges; values of any other
// registry type are ignored.
//
// Part of NERCFilt.  SPDX-License-Identifier: MIT

#pragma once

#include "Platform.h"

#include <cstddef>

namespace nercfilt {

constexpr unsigned long kCipMinimumLength = 8;   // CIP-007-6 R5.5.1
constexpr unsigned long kCipMinimumClasses = 3;  // CIP-007-6 R5.5.2
constexpr unsigned long kMaximumLength = 256;    // longest Windows password
constexpr unsigned long kCharacterClasses = 4;   // upper, lower, digit, symbol

constexpr wchar_t kPolicyKey[] = L"SOFTWARE\\NERCFilt";
constexpr wchar_t kMinimumLengthValue[] = L"MinimumLength";
constexpr wchar_t kMinimumClassesValue[] = L"MinimumCharacterClasses";

struct Policy {
  unsigned long minimumLength = kCipMinimumLength;
  unsigned long minimumClasses = kCipMinimumClasses;
};

// Clamp requested settings into the permitted (CIP-or-stricter) range.
Policy MakePolicy(unsigned long requestedLength,
                  unsigned long requestedClasses) noexcept;

// Read the policy from the registry; defaults for anything missing.
Policy LoadPolicy() noexcept;

// True if `password` (cch UTF-16 code units, not necessarily terminated)
// satisfies `policy`.  Never reads beyond password[cch - 1].
bool MeetsPolicy(const wchar_t *password, std::size_t cch,
                 const Policy &policy) noexcept;

// Computer, inter-domain trust and (g)MSA accounts have names ending in '$'.
// Their passwords are generated by Windows and must not be filtered.
bool IsExemptAccount(const wchar_t *name, std::size_t cch) noexcept;

} // namespace nercfilt
